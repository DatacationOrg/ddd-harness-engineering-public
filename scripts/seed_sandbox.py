def _shipments_csv() -> bytes:
    buffer = io.StringIO(newline="")
    # An explicit line terminator keeps the bytes identical on every platform.
    writer = csv.writer(buffer, lineterminator="\n")
    writer.writerow(SHIPMENTS_COLUMNS)
