def _tiny_jpeg(label: str, tone: int) -> bytes:
    """A valid baseline JPEG: one grayscale 8x8 block at the given tone."""
    jfif = b"JFIF\x00" + bytes((1, 1, 0)) + struct.pack(">HH", 1, 1) + bytes((0, 0))
    segments = (
        _jpeg_segment(0xE0, jfif),
        _jpeg_segment(0xFE, label.encode("ascii", "replace")),
        _jpeg_segment(0xDB, b"\x00" + bytes([16] * 64)),
        _jpeg_segment(0xC0, struct.pack(">BHHB", 8, 8, 8, 1) + bytes((1, 0x11, 0))),
        _jpeg_segment(0xC4, b"\x00" + bytes(_JPEG_DC_BITS) + bytes(_JPEG_DC_VALUES)),
        _jpeg_segment(0xC4, b"\x10" + bytes(_JPEG_AC_BITS) + bytes(_JPEG_AC_VALUES)),
        _jpeg_segment(0xDA, bytes((1, 1, 0x00, 0, 63, 0))),
    )
    return b"\xff\xd8" + b"".join(segments) + _jpeg_scan(tone) + b"\xff\xd9"


def _jpeg_segment(marker: int, payload: bytes) -> bytes:
    return bytes((0xFF, marker)) + struct.pack(">H", len(payload) + 2) + payload


def _jpeg_scan(tone: int) -> bytes:
    """Entropy-code a single block: one DC coefficient, then end-of-block."""
    dc_codes = _huffman_codes(_JPEG_DC_BITS, _JPEG_DC_VALUES)
    ac_codes = _huffman_codes(_JPEG_AC_BITS, _JPEG_AC_VALUES)
    bits = _BitWriter()
    category = tone.bit_length()
    bits.write(*dc_codes[category])
    bits.write(tone, category)
    bits.write(*ac_codes[0x00])
    return bits.flush()


def _huffman_codes(
    counts: Sequence[int], symbols: Sequence[int]
) -> dict[int, tuple[int, int]]:
    codes: dict[int, tuple[int, int]] = {}
    code = 0
    index = 0
    for length, count in enumerate(counts, start=1):
        for _ in range(count):
            codes[symbols[index]] = (code, length)
            index += 1
            code += 1
        code <<= 1
    return codes


class _BitWriter:
    def __init__(self) -> None:
        self._bits: list[str] = []

    def write(self, value: int, length: int) -> None:
        if length:
            self._bits.append(format(value, f"0{length}b"))

    def flush(self) -> bytes:
        stream = "".join(self._bits)
        stream += "1" * (-len(stream) % 8)
        payload = bytearray()
        for start in range(0, len(stream), 8):
            byte = int(stream[start : start + 8], 2)
            payload.append(byte)
            if byte == 0xFF:
                payload.append(0x00)  # byte stuffing
        return bytes(payload)


def _tiny_png(width: int, height: int, variant: int) -> bytes:
    raw = bytearray()
    for y in range(height):
        raw.append(0)  # filter type: none
        for x in range(width):
            raw.append((x * 5 + variant * 40) % 256)
            raw.append((y * 9 + variant * 25) % 256)
            raw.append((x * y + variant * 70) % 256)

    header = struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)
    return (
        b"\x89PNG\r\n\x1a\n"
        + _png_chunk(b"IHDR", header)
        + _png_chunk(b"IDAT", _deflate_stored(bytes(raw)))
        + _png_chunk(b"IEND", b"")
    )


def _png_chunk(tag: bytes, payload: bytes) -> bytes:
    return (
        struct.pack(">I", len(payload))
        + tag
        + payload
        + struct.pack(">I", zlib.crc32(tag + payload))
    )


def _deflate_stored(data: bytes) -> bytes:
    """Wrap `data` in uncompressed deflate blocks.

    zlib's compressed output is not guaranteed identical across zlib builds;
    stored blocks are, which keeps the fixture byte-for-byte reproducible.
    """
    chunks = [
        data[start : start + 0xFFFF] for start in range(0, len(data), 0xFFFF)
    ] or [b""]
    stream = bytearray(b"\x78\x01")
    for index, chunk in enumerate(chunks):
        stream.append(1 if index == len(chunks) - 1 else 0)
        stream += struct.pack("<HH", len(chunk), len(chunk) ^ 0xFFFF)
        stream += chunk
    stream += struct.pack(">I", zlib.adler32(data))
    return bytes(stream)


