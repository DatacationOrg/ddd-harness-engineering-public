def _pdf(title: str, lines: Sequence[str]) -> bytes:
    """Build a small but genuinely valid PDF 1.4 document."""
    content = _pdf_content(title, lines)
    objects = [
        b"<</Type/Catalog/Pages 2 0 R>>",
        b"<</Type/Pages/Kids[3 0 R]/Count 1>>",
        b"<</Type/Page/Parent 2 0 R/MediaBox[0 0 595 842]"
        b"/Resources<</Font<</F1 5 0 R>>>>/Contents 4 0 R>>",
        b"<</Length %d>>\nstream\n%s\nendstream" % (len(content), content),
        b"<</Type/Font/Subtype/Type1/BaseFont/Courier>>",
    ]

    document = bytearray(b"%PDF-1.4\n")
    offsets: list[int] = []
    for number, body in enumerate(objects, start=1):
        offsets.append(len(document))
        document += b"%d 0 obj\n" % number + body + b"\nendobj\n"

    start_xref = len(document)
    document += b"xref\n0 %d\n" % (len(objects) + 1)
    document += b"0000000000 65535 f \n"
    for offset in offsets:
        document += b"%010d 00000 n \n" % offset
    document += b"trailer\n<</Size %d/Root 1 0 R>>\nstartxref\n%d\n%%%%EOF\n" % (
        len(objects) + 1,
        start_xref,
    )
    return bytes(document)


def _pdf_content(title: str, lines: Sequence[str]) -> bytes:
    parts = [b"BT\n/F1 10 Tf\n56 780 Td\n14 TL\n"]
    for line in (title, "", *lines):
        parts.append(b"(%s) Tj\nT*\n" % _pdf_escape(line))
    parts.append(b"ET")
    return b"".join(parts)


def _pdf_escape(text: str) -> bytes:
    escaped = text.replace("\\", r"\\").replace("(", r"\(").replace(")", r"\)")
    return escaped.encode("latin-1", "replace")


def _xlsx(rows: Sequence[Sequence[str]]) -> bytes:
    """Build a minimal, openable .xlsx workbook (inline strings only)."""
    body: list[str] = []
    for row_number, row in enumerate(rows, start=1):
        cells = "".join(
            f'<c r="{_column_name(position)}{row_number}" t="inlineStr">'
            f"<is><t>{_xml_escape(value)}</t></is></c>"
            for position, value in enumerate(row)
            if value != ""
        )
        body.append(f'<row r="{row_number}">{cells}</row>')

    sheet = (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
        '<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">'
        f"<sheetData>{''.join(body)}</sheetData></worksheet>"
    )
    workbook = (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
        '<workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"'
        ' xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">'
        '<sheets><sheet name="Sheet1" sheetId="1" r:id="rId1"/></sheets></workbook>'
    )
    return _ooxml(
        {
            "[Content_Types].xml": _content_types(
                {
                    "/xl/workbook.xml": (
                        "application/vnd.openxmlformats-officedocument."
                        "spreadsheetml.sheet.main+xml"
                    ),
                    "/xl/worksheets/sheet1.xml": (
                        "application/vnd.openxmlformats-officedocument."
                        "spreadsheetml.worksheet+xml"
                    ),
                }
            ),
            "_rels/.rels": _relationships(
                {"rId1": ("officeDocument", "xl/workbook.xml")}
            ),
            "xl/workbook.xml": workbook,
            "xl/_rels/workbook.xml.rels": _relationships(
                {"rId1": ("worksheet", "worksheets/sheet1.xml")}
            ),
            "xl/worksheets/sheet1.xml": sheet,
        }
    )


def _docx(title: str, paragraphs: Sequence[str]) -> bytes:
    """Build a minimal, openable .docx document."""
    namespace = "http://schemas.openxmlformats.org/wordprocessingml/2006/main"
    body = "".join(
        f'<w:p><w:r><w:t xml:space="preserve">{_xml_escape(text)}</w:t></w:r></w:p>'
        for text in (title, "", *paragraphs)
    )
    document = (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
        f'<w:document xmlns:w="{namespace}"><w:body>{body}</w:body></w:document>'
    )
    return _ooxml(
        {
            "[Content_Types].xml": _content_types(
                {
                    "/word/document.xml": (
                        "application/vnd.openxmlformats-officedocument."
                        "wordprocessingml.document.main+xml"
                    )
                }
            ),
            "_rels/.rels": _relationships(
                {"rId1": ("officeDocument", "word/document.xml")}
            ),
            "word/document.xml": document,
        }
    )


def _content_types(overrides: dict[str, str]) -> str:
    parts = "".join(
        f'<Override PartName="{name}" ContentType="{content_type}"/>'
        for name, content_type in overrides.items()
    )
    return (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
        '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'
        '<Default Extension="rels" ContentType="application/vnd.openxmlformats-'
        'package.relationships+xml"/>'
        '<Default Extension="xml" ContentType="application/xml"/>'
        f"{parts}</Types>"
    )


def _relationships(entries: dict[str, tuple[str, str]]) -> str:
    base = "http://schemas.openxmlformats.org/officeDocument/2006/relationships"
    parts = "".join(
        f'<Relationship Id="{identifier}" Type="{base}/{kind}" Target="{target}"/>'
        for identifier, (kind, target) in entries.items()
    )
    return (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
        '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/'
        f'relationships">{parts}</Relationships>'
    )


def _ooxml(parts: dict[str, str]) -> bytes:
    """Zip the OOXML parts with fixed metadata so the bytes are stable."""
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w") as archive:
        for name, payload in parts.items():
            info = zipfile.ZipInfo(name, date_time=(2026, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_STORED
            info.external_attr = 0o600 << 16
            archive.writestr(info, payload.encode("utf-8"))
    return buffer.getvalue()


def _column_name(position: int) -> str:
    name = ""
    position += 1
    while position:
        position, remainder = divmod(position - 1, 26)
        name = chr(ord("A") + remainder) + name
    return name


def _xml_escape(text: str) -> str:
    return (
        text.replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
    )


