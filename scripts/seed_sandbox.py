def _set_age(path: Path, relative: str) -> None:
    seconds = _MTIME_BASE - _age_days(relative) * 86_400
    os.utime(path, (seconds, seconds))


def _age_days(relative: str) -> int:
    days = 3 + zlib.crc32(relative.encode("utf-8")) % 540
    if relative.startswith(("archive/", "Reports/old/")):
        days += 1_800
    return days


def _set_directory_ages(root: Path) -> None:
    for path in sorted(root.rglob("*"), reverse=True):
        if path.is_dir():
            _set_age(path, path.relative_to(root).as_posix())
    _set_age(root, "")


