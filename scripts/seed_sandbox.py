"""Seed the fictional Northwind Freight drive used as the workshop sandbox.

The Datacation "Harness Engineering" day needs a filesystem that is relatable,
genuinely messy, and completely disposable: participants point a deep agent at
it, hand the agent real destructive power, and then break things on purpose.
Nothing in here is real -- every company, person, invoice and shipment is
invented -- so the whole tree can be deleted and regenerated at any time with:

    uv run python scripts/seed_sandbox.py --reset

The output is deterministic: the same seed always produces the same bytes, so
every participant and every CI run gets an identical fixture. Three fixtures
are contracts that other stations code against, exported as module-level
constants:

* `DUPLICATE_GROUP` -- the one and only set of byte-identical files (S2, S8).
* `SHIPMENTS_CSV` -- a freight extract with planted data-quality issues (S4).
* `INJECTION_FILES` -- planted prompt-injection payloads (S3).

Plus `WORKSPACE_DIR`, the empty directory that stays writable once the
`FilesystemPermission` rules from S2 land.

This script deletes directories, so it refuses to touch anything that is not
inside the repository's `sandbox/` directory.
"""

