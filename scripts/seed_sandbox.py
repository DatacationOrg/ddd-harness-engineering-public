# --- Safety -----------------------------------------------------------------


def _resolve_within_sandbox(root: Path) -> Path:
    """Resolve `root` and refuse anything outside the repo sandbox directory.

    This script calls `shutil.rmtree`, so containment is checked on the fully
    resolved path (symlinks included) before anything is deleted.
    """
    resolved = root.expanduser().resolve()
    sandbox = SANDBOX_DIR.resolve()
    if resolved == sandbox or not resolved.is_relative_to(sandbox):
        raise SandboxPathError(
            f"refusing to touch {resolved}: the sandbox root must be a "
            f"directory inside {sandbox}"
        )
    return resolved


def _prepare_root(root: Path, *, reset: bool) -> None:
    if root.exists() and any(root.iterdir()):
        if not reset:
            raise FileExistsError(
                f"{root} already exists and is not empty. "
                f"Re-run with --reset to delete and regenerate it."
            )
        # Checked again here: nothing is removed without a containment test.
        _resolve_within_sandbox(root)
        shutil.rmtree(root)

    root.mkdir(parents=True, exist_ok=True)


